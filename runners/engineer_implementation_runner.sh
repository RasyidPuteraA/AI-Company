from pathlib import Path
import sys

handover_file = Path(sys.argv[1])
project_key = sys.argv[2]
task_key = sys.argv[3]
pm_analysis_file = sys.argv[4]
site_dir = sys.argv[5]

marker = f"\n## Engineer Implementation Completed for {task_key}\n"
text = handover_file.read_text() if handover_file.exists() else ""

if marker in text:
    text = text.split(marker)[0].rstrip() + "\n"

block = f"""
## Engineer Implementation Completed for {task_key}

Project:

    {project_key}

Output folder:

    {site_dir}

Source PM analysis:

    {pm_analysis_file}

Files created:

- site/index.html
- site/styles.css
- site/app.js
- site/README.md

Status:

- Initial implementation output created.
- Ready for QA review.
"""

handover_file.write_text(text.rstrip() + "\n\n" + block.strip() + "\n")
PY

"$ROOT_DIR/runners/log_event.sh" \
  "$PROJECT_KEY" \
  "$TASK_KEY" \
  "engineer_agent" \
  "engineer_implementation_completed" \
  "IMPLEMENTED" \
  "engineering_desk" \
  "Engineer implementation output created" \
  "Engineer implementation runner created initial site output for $TASK_KEY."

"$ROOT_DIR/runners/update_task_status.sh" \
  "$TASK_KEY" \
  "IMPLEMENTED" \
  "Engineer implementation runner created initial site output under projects/clients/${PROJECT_KEY}/site."

echo "Engineer implementation completed:"
echo "- Project: $PROJECT_KEY"
echo "- Task: $TASK_KEY"
echo "- Output: $SITE_DIR"
echo "- PM analysis: $PM_ANALYSIS_FILE"

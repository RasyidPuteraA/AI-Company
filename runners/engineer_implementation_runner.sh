</head>
<body>
  <header class="hero">
    <nav class="nav">
      <div class="brand">AI Company Client Demo</div>
      <a href="#contact" class="nav-cta">Contact</a>
    </nav>

    <section class="hero-content">
      <p class="eyebrow">Generated by AI Company OS</p>
      <h1>Modern Company Profile Website</h1>
      <p class="hero-copy">
        This v0 implementation was generated from the PM intake analysis and project upload context.
      </p>
      <div class="hero-actions">
        <a href="#services" class="button primary">View Services</a>
        <a href="#process" class="button secondary">See Process</a>
      </div>
    </section>
  </header>

  <main>
    <section class="panel" id="requirement">
      <p class="eyebrow">Requirement Source</p>
      <h2>Owner Requirement</h2>
      <p>{escaped_requirement}</p>
    </section>

    <section class="grid" id="services">
      <article class="card">
        <h3>Company Profile</h3>
        <p>Clear landing page structure for presenting services, brand value, and contact paths.</p>
      </article>
      <article class="card">
        <h3>Responsive Layout</h3>
        <p>Mobile-friendly static layout suitable for quick preview and future iteration.</p>
      </article>
      <article class="card">
        <h3>Client Intake Ready</h3>
        <p>Built as a starting point for QA review and owner/client revision.</p>
      </article>
    </section>

    <section class="panel" id="process">
      <p class="eyebrow">Delivery Process</p>
      <h2>From Requirement to Preview</h2>
      <ol class="steps">
        <li>Owner submits requirement through dashboard.</li>
        <li>PM analysis creates implementation direction.</li>
        <li>Engineer produces initial website output.</li>
        <li>QA verifies against requirement and uploaded assets.</li>
      </ol>
    </section>

    <section class="panel contact" id="contact">
      <p class="eyebrow">Next Step</p>
      <h2>Ready for QA Review</h2>
      <p>This implementation is ready for QA verification and owner feedback.</p>
    </section>
  </main>

  <footer>
    <span>Project: {html.escape(project_key)}</span>
    <span>Task: {html.escape(task_key)}</span>
    <span>Source: {html.escape(pm_task_key)}</span>
  </footer>

  <script src="app.js"></script>
</body>
</html>
""")


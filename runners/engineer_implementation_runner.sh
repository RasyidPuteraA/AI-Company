#!/usr/bin/env bash
set -euo pipefail

PROJECT_KEY="${1:-}"
TASK_KEY="${2:-}"

if [[ -z "$PROJECT_KEY" || -z "$TASK_KEY" ]]; then
  echo "Usage:"
  echo "  ./runners/engineer_implementation_runner.sh <project_key> <engineer_task_key>"
  echo
  echo "Example:"
  echo "  ./runners/engineer_implementation_runner.sh client-company-profile-demo CLIENT-1-ENG-001"
  exit 1
fi

if ! [[ "$PROJECT_KEY" =~ ^[a-z0-9][a-z0-9-]*$ ]]; then
  echo "ERROR: project_key must use lowercase letters, numbers, and dashes only."
  exit 1
fi

if ! [[ "$TASK_KEY" =~ ^[A-Z0-9-]+$ ]]; then
  echo "ERROR: task_key must use uppercase letters, numbers, and dashes only."
  exit 1
fi

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_DIR="$ROOT_DIR/projects/clients/$PROJECT_KEY"
TASK_FILE="$PROJECT_DIR/$TASK_KEY.md"
HANDOVER_FILE="$PROJECT_DIR/AGENT_HANDOVER.md"
SITE_DIR="$PROJECT_DIR/site"

SOURCE_ID="$(echo "$TASK_KEY" | sed -E 's/^CLIENT-([0-9]+)-.*/\1/')"
PM_TASK_KEY="CLIENT-${SOURCE_ID}-001"
PM_ANALYSIS_FILE="$PROJECT_DIR/PM_INTAKE_ANALYSIS-${PM_TASK_KEY}.md"

if [[ ! -d "$PROJECT_DIR" ]]; then
  echo "ERROR: project directory not found: $PROJECT_DIR"
  exit 1
fi

if [[ ! -f "$TASK_FILE" ]]; then
  echo "ERROR: engineer task file not found: $TASK_FILE"
  exit 1
fi

if [[ ! -f "$PM_ANALYSIS_FILE" ]]; then
  echo "ERROR: PM analysis file not found: $PM_ANALYSIS_FILE"
  exit 1
fi

mkdir -p "$SITE_DIR"

python3 - "$PROJECT_KEY" "$TASK_KEY" "$PM_TASK_KEY" "$PM_ANALYSIS_FILE" "$SITE_DIR" << 'PY'
from pathlib import Path
import html
import sys

project_key = sys.argv[1]
task_key = sys.argv[2]
pm_task_key = sys.argv[3]
pm_analysis_file = Path(sys.argv[4])
site_dir = Path(sys.argv[5])

analysis = pm_analysis_file.read_text()

requirement = "Client project generated from PM intake analysis."
capture = False
collected = []

for line in analysis.splitlines():
    if line.strip() == "## Requirement Summary":
        capture = True
        continue
    if capture and line.startswith("## "):
        break
    if capture:
        collected.append(line)

cleaned = "\n".join(collected).strip()
if cleaned:
    requirement = cleaned.replace(">", "").strip()

escaped_requirement = html.escape(requirement)
title = "Client Company Profile Demo"

(site_dir / "index.html").write_text(f"""<!doctype html>
<html lang="en">
